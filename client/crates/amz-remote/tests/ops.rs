#[tokio::test]
async fn delete_client_revokes_peer_or_keeps_it_when_server_fails() {
    let mut env = setup(true).await;
    let (cid, made) = adopt_praga_and_add_client(&mut env).await;
    assert!(env.file(EXIT_IP, "/opt/amnezia/awg/wg0.conf").contains("10.8.1.2/32"));
    let r = ops::delete_client(&env.conn, &env.store, &mut env.s, &made).await;
    assert!(r.ok && r.log[0].contains("отозван"), "{:?}", r.log);
    assert!(!env.file(EXIT_IP, "/opt/amnezia/awg/wg0.conf").contains("10.8.1.2/32"));
    assert!(env.s.clients.is_empty());
    assert!(!ops::delete_client(&env.conn, &env.store, &mut env.s, &made).await.ok);

    let made = ops::create_clients(&env.conn, &env.store, &mut env.s, "phone", &[cid]).await.unwrap();
    env.host(EXIT_IP).down = true;
    let r = ops::delete_client(&env.conn, &env.store, &mut env.s, &made[0]).await;
    assert!(!r.ok && r.log.last().unwrap().contains("ssh down"));
    assert_eq!(env.s.clients.len(), 1); // not lost from the list
}

#[tokio::test]
async fn traffic_accumulates_and_survives_counter_reset() {
    let mut env = setup(true).await;
    let (_, made) = adopt_praga_and_add_client(&mut env).await;
    let pubkey = env.s.clients[0].public_key.clone();
    let set = |env: &Env, rx: u64, tx: u64| {
        env.host(EXIT_IP).answers = vec![
            ("show wg0 transfer".into(), format!("{pubkey}\t{rx}\t{tx}\nOTHERKEY\t5\t5\n")),
            ("show wg0 latest-handshakes".into(), format!("{pubkey}\t1790000000\n")),
        ];
    };
    set(&env, 1000, 2000);
    let r = ops::refresh_traffic(&env.conn, &env.store, &mut env.s).await;
    assert!(r.ok && r.log == ["praga: обновлено клиентов 1"], "{:?}", r.log);
    let c = &env.s.clients[0];
    assert_eq!((c.traffic.unwrap().rx, c.traffic.unwrap().tx, c.handshake), (1000, 2000, Some(1790000000)));
    assert!(c.stats_at.is_some() && c.id == made);

    set(&env, 1500, 2500); // more traffic
    ops::refresh_traffic(&env.conn, &env.store, &mut env.s).await;
    assert_eq!(env.s.clients[0].traffic, Some(amz_core::model::Traffic { rx: 1500, tx: 2500 }));

    set(&env, 100, 200); // interface restarted: counters start over
    ops::refresh_traffic(&env.conn, &env.store, &mut env.s).await;
    assert_eq!(env.s.clients[0].traffic, Some(amz_core::model::Traffic { rx: 1600, tx: 2700 }));

    env.host(EXIT_IP).down = true;
    let r = ops::refresh_traffic(&env.conn, &env.store, &mut env.s).await;
    assert!(!r.ok && r.log[0].contains("ssh down"), "{:?}", r.log);
    assert_eq!(env.s.clients[0].traffic, Some(amz_core::model::Traffic { rx: 1600, tx: 2700 })); // kept as is
}

#[tokio::test]
async fn cascade_with_awg3_container() {
    let mut env = setup(true).await;
    {
        let mut h = env.host(EXIT2_IP);
        h.containers.clear();
        h.starts = Some("cascade-awg-v3".into());
        h.answers.push(("iptables -t nat -S POSTROUTING".into(), "-A POSTROUTING -s 10.9.3.0/24 -o eth0 -j MASQUERADE\n".into()));
    }
    // the container reports the port it was started with
    let conn_hosts = env.conn.0.clone();
    let waiter = tokio::spawn(async move {
        loop {
            tokio::time::sleep(Duration::from_millis(100)).await;
            let mut h = conn_hosts[EXIT2_IP].lock().unwrap();
            if let Some(conf) = h.files.get("/opt/cascade/awgv3.conf").cloned() {
                let lp = parse_conf(&conf).0["ListenPort"].clone();
                h.answers.push(("awg show awgv3 listen-port".into(), lp));
                break;
            }
        }
    });
    let r = { let req = env.cascade_req(&["nl"], None, "v3"); ops::create_cascades(&env.conn, &env.store, &mut env.s, &req).await };
    waiter.await.unwrap();
    assert!(r.ok, "{:?}", r.log);
    let v = ops::cascade_views(&env.conn, &env.s).into_iter().find(|v| v.cascade.exit_id == env.ids["nl"]).unwrap();
    assert_eq!((v.cascade.instance(), v.awg_version.as_deref()), ("v3", Some("3.x")));
    let made = ops::create_clients(&env.conn, &env.store, &mut env.s, "laptop", std::slice::from_ref(&v.cascade.id)).await.unwrap();
    let conf = ops::render(&env.s, &made[0]).unwrap().conf;
    assert!(conf.contains("Address = 10.9.3.2/32") && conf.contains("HeaderProtectionKey = "), "{conf}");
    assert!(!env.file(EXIT2_IP, "/opt/amnezia/awg/wg0.conf").contains("10.9.3.2")); // main instance untouched
}

