fn server_conf(priv_key: &str, port: u16) -> String {
    format!("[Interface]\nPrivateKey = {priv_key}\nAddress = 10.8.1.0/24\nListenPort = {port}\nJc = 4\nJmin = 10\nJmax = 50\n\
             S1 = 97\nS2 = 34\nH1 = 111\nH2 = 222\nH3 = 333\nH4 = 444\n\n[Peer]\nPublicKey = AAA\nPresharedKey = BBB\nAllowedIPs = 10.8.1.1/32\n")
}

/// A fake server: the proxy (NAT table built from our rules script) or an AmneziaVPN exit (container with files).
#[derive(Default)]
struct Host {
    proxy: bool,
    files: HashMap<String, String>,
    containers: Vec<String>,
    /// probes that arrive at this host
    arrived: u32,
    down: bool,
    /// overrides: command substring -> answer
    answers: Vec<(String, String)>,
    /// `docker run` starts this container
    starts: Option<String>,
}

impl Host {
    fn exit(port: u16) -> Self {
        let mut h = Host { arrived: 5, containers: vec!["amnezia-awg".into(), "amnezia-dns".into()], ..Default::default() };
        h.files.insert("/opt/amnezia/awg/wg0.conf".into(), server_conf(&keys::gen_private_key(), port));
        h.files.insert("/opt/amnezia/awg/wireguard_psk.key".into(), "SHAREDPSK\n".into());
        h
    }

    fn run(&mut self, cmd: &str, input: Option<&str>) -> Result<String> {
        if self.down {
            bail!("ssh down");
        }
        if let Some((_, a)) = self.answers.iter().find(|(k, _)| cmd.contains(k.as_str())) {
            return Ok(a.clone());
        }
        if cmd.starts_with("iptables -t raw -L CASCADE_PROBE") {
            return Ok(format!(" {} 100 RETURN udp\n", self.arrived));
        }
        if let Some(rest) = cmd.strip_prefix("cat > ") {
            let path = rest.split(" && ").next().unwrap().trim_matches('\'');
            let path = path.replace("/opt/cascade-awg-v3", "/opt/cascade");
            self.files.insert(path, input.unwrap_or_default().into());
            return Ok(String::new());
        }
        if self.proxy {
            if cmd.starts_with("iptables-save") {
                let script = self.files.get(proxy::SCRIPT_PATH).cloned().unwrap_or_default();
                let ours: Vec<String> = script.lines().filter(|l| l.starts_with("iptables -t nat -A CASCADE_PRE"))
                    .map(|l| l.replace("iptables -t nat -A", "-A")).collect();
                return Ok(format!("{NAT}{}\n", ours.join("\n")));
            }
            return Ok(String::new());
        }
        if cmd.starts_with("command -v docker >/dev/null && echo yes") {
            return Ok("yes\n".into());
        }
        if cmd.starts_with("command -v docker") {
            return Ok(self.containers.join("\n") + "\n");
        }
        if cmd.contains("docker run") {
            self.containers.extend(self.starts.clone());
            return Ok(String::new());
        }
        if cmd.starts_with("docker exec -i ") {
            let inner = shlex::split(cmd).unwrap().pop().unwrap();
            if inner.starts_with("ls ") {
                return Ok("/opt/amnezia/awg/wg0.conf\n".into());
            }
            if inner.starts_with("command -v awg") {
                return Ok("wg\n".into());
            }
            let words: Vec<&str> = inner.split_whitespace().collect();
            if inner.starts_with("cat >> ") {
                self.files.get_mut(words[2]).unwrap().push_str(input.unwrap());
                return Ok(String::new());
            }
            if inner.starts_with("cat > ") {
                self.files.insert(words[2].into(), input.unwrap().into());
                return Ok(String::new());
            }
            if inner.starts_with("cat ") {
                return Ok(self.files.get(words[1]).cloned().unwrap_or_default());
            }
        }
        Ok(String::new())
    }
}

type Hosts = Arc<HashMap<String, Arc<Mutex<Host>>>>;

struct FakeRemote {
    host: String,
    h: Arc<Mutex<Host>>,
}

impl Remote for FakeRemote {
    fn host(&self) -> &str {
        &self.host
    }
    async fn exec(&mut self, cmd: &str, input: Option<&str>, _check: bool, _t: Duration) -> Result<String> {
        self.h.lock().unwrap().run(cmd, input)
    }
    async fn reconnect(&mut self) -> Result<()> {
        Ok(())
    }
}

struct FakeConn(Hosts);

impl Connector for FakeConn {
    type R = FakeRemote;
    async fn connect(&self, s: &Server) -> Result<FakeRemote> {
        let h = self.0.get(&s.host).ok_or_else(|| anyhow!("no host {}", s.host))?.clone();
        Ok(FakeRemote { host: s.host.clone(), h })
    }
    fn ip_of(&self, s: &Server) -> String {
        s.host.clone()
    }
}

struct Env {
    conn: FakeConn,
    store: Storage,
    s: State,
    ids: HashMap<&'static str, String>,
    _dir: TempDir,
}

struct TempDir(std::path::PathBuf);
impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

impl Env {
    fn host(&self, ip: &str) -> std::sync::MutexGuard<'_, Host> {
        self.conn.0[ip].lock().unwrap()
    }
    fn file(&self, ip: &str, path: &str) -> String {
        self.host(ip).files.get(path).cloned().unwrap_or_default()
    }
    fn cascade_req(&self, exits: &[&str], port: Option<u16>, instance: &str) -> CascadeRequest {
        CascadeRequest { proxy_id: self.ids["proxy"].clone(), exit_ids: exits.iter().map(|e| self.ids[e].clone()).collect(),
                         port, instance: instance.into() }
    }
}

async fn setup(scan: bool) -> Env {
    tokio::time::pause();
    let mut exit = Host::exit(48303);
    exit.arrived = 5;
    let hosts: HashMap<String, Arc<Mutex<Host>>> = [
        (PROXY_IP, Host { proxy: true, arrived: 5, ..Default::default() }),
        (EXIT_IP, exit),
        (EXIT2_IP, Host::exit(43210)),
    ].into_iter().map(|(k, v)| (k.to_string(), Arc::new(Mutex::new(v)))).collect();
    let dir = std::env::temp_dir().join(format!("amz-ops-{}", ops::new_id()));
    let mut env = Env { conn: FakeConn(Arc::new(hosts)), store: Storage::new(&dir), s: State::default(),
                        ids: HashMap::new(), _dir: TempDir(dir) };
    for (name, host) in [("proxy", PROXY_IP), ("praga", EXIT_IP), ("nl", EXIT2_IP)] {
        let id = ops::new_id();
        env.s.servers.push(Server { id: id.clone(), name: name.into(), host: host.into(), ssh_port: 22,
                                    user: "root".into(), ..Default::default() });
        env.ids.insert(name, id.clone());
        if scan {
            ops::scan_server(&env.conn, &env.store, &mut env.s, &id).await.unwrap();
        }
    }
    env
}

async fn adopt_praga_and_add_client(env: &mut Env) -> (String, String) {
    let (p, e) = (env.ids["proxy"].clone(), env.ids["praga"].clone());
    ops::adopt_cascade(&env.conn, &env.store, &mut env.s, &p, &e, 48303).unwrap();
    let cid = env.s.cascades[0].id.clone();
    let made = ops::create_clients(&env.conn, &env.store, &mut env.s, "phone", std::slice::from_ref(&cid)).await.unwrap();
    (cid, made[0].clone())
}

#[tokio::test]
async fn existing_cascade_is_highlighted_and_adoptable() {
    let mut env = setup(true).await;
    let ext = ops::external_not_adopted(&env.conn, &env.s);
    assert_eq!(ext.len(), 1);
    assert_eq!((ext[0].port, ext[0].rule.as_str()), (48303, "udp 48303 → 203.0.113.9:48303 (amnezia-relay-48303)"));

    let (_, client) = adopt_praga_and_add_client(&mut env).await;
    assert!(ops::external_not_adopted(&env.conn, &env.s).is_empty());
    assert_eq!(ops::cascade_views(&env.conn, &env.s)[0].status, "external");
    assert!(!env.host(PROXY_IP).files.contains_key(proxy::SCRIPT_PATH)); // nothing written to the proxy
    let r = ops::render(&env.s, &client).unwrap();
    assert!(r.conf.contains("Endpoint = 198.51.100.1:48303"));
    assert!(r.conf.contains("Address = 10.8.1.2/32") && r.conf.contains("PresharedKey = SHAREDPSK"));
    assert_eq!(r.filename, "phone_proxy_praga.conf");
    // the saved file matches what is in memory
    assert_eq!(env.store.load().unwrap(), env.s);
}

#[tokio::test]
async fn managed_cascade_avoids_existing_ports() {
    let mut env = setup(true).await;
    let r = { let req = env.cascade_req(&["nl"], Some(51820), "auto"); ops::create_cascades(&env.conn, &env.store, &mut env.s, &req).await };
    assert!(!r.ok && r.log.last().unwrap().contains("10000:60000"), "{:?}", r.log);
    assert!(!env.host(PROXY_IP).files.contains_key(proxy::SCRIPT_PATH));

    let r = { let req = env.cascade_req(&["nl", "praga"], None, ""); ops::create_cascades(&env.conn, &env.store, &mut env.s, &req).await };
    assert!(r.ok, "{:?}", r.log);
    assert!(r.log.iter().any(|l| l.contains("уже есть существующий каскад"))); // praga already relayed via 48303
    let script = env.file(PROXY_IP, proxy::SCRIPT_PATH);
    assert!(script.contains("--dport 60001 -j DNAT --to-destination 192.0.2.5:43210"), "{script}");
    assert!(script.contains("--dport 60002 -j DNAT --to-destination 203.0.113.9:48303"));
    let views = ops::cascade_views(&env.conn, &env.s);
    assert_eq!(views.iter().map(|v| v.status.as_str()).collect::<Vec<_>>(), ["applied", "applied"]);

    let cids: Vec<String> = env.s.cascades.iter().map(|c| c.id.clone()).collect();
    let made = ops::create_clients(&env.conn, &env.store, &mut env.s, "phone", &cids).await.unwrap();
    let doc = decode_vpn_key(&ops::render(&env.s, &made[0]).unwrap().vpn_key).unwrap();
    assert_eq!(doc["hostName"], PROXY_IP);
    assert_eq!(doc["containers"][0]["awg"]["port"], "60001");

    // one key with both exits: the chosen one is the default, the other is in our extension
    let (_, exits) = ops::render_all(&env.s, &made[1]).unwrap();
    assert_eq!(exits.iter().map(|e| e.name.as_str()).collect::<Vec<_>>(), ["praga", "nl"]);
    let imported = amz_core::import_vpn_key(&ops::render_all(&env.s, &made[1]).unwrap().0.vpn_key).unwrap();
    assert_eq!((imported.name.as_str(), imported.exits.len()), ("phone", 2));
    assert!(imported.conf.contains(":60002") && imported.exits[1].conf.contains(":60001"));

    let r = ops::delete_cascade(&env.conn, &env.store, &mut env.s, &cids[0]).await;
    assert!(r.ok, "{:?}", r.log);
    let script = env.file(PROXY_IP, proxy::SCRIPT_PATH);
    assert!(!script.contains("60001") && script.contains("60002"));
    assert_eq!(env.s.clients.len(), 1);
}

